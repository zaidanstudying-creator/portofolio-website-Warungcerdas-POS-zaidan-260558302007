create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  role text not null default 'kasir' check (role in ('admin','kasir')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique, sort_order integer not null default 0, is_active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete restrict,
  name text not null, price numeric(12,2) not null check (price >= 0), hpp numeric(12,2) check (hpp >= 0),
  image text, is_available boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.toppings (
  id bigint generated by default as identity primary key,
  name text not null unique, price numeric(12,2) not null check (price >= 0), hpp numeric(12,2) check (hpp >= 0),
  image text, is_available boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.product_topping (
  product_id bigint not null references public.products(id) on delete cascade,
  topping_id bigint not null references public.toppings(id) on delete cascade,
  primary key(product_id,topping_id)
);
create table public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  type text not null check(type in ('DLV','DI','TA')),
  status text not null default 'preparing' check(status in ('new','preparing','ready','completed','cancelled')),
  customer_name text, table_number text, delivery_address text, delivery_platform text,
  subtotal numeric(12,2) not null, total numeric(12,2) not null,
  discount_type text check(discount_type in ('fixed','percentage')), discount_value numeric(12,2) not null default 0,
  discount_amount numeric(12,2) not null default 0, additional_fee_label text, additional_fee_amount numeric(12,2) not null default 0,
  payment_method text check(payment_method in ('cash','qris')), amount_paid numeric(12,2), change numeric(12,2),
  payment_status text not null default 'unpaid' check(payment_status in ('unpaid','paid')), paid_at timestamptz,
  notes text, created_by uuid references public.profiles(id) on delete set null,
  idempotency_key uuid, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index orders_idempotency_key_unique on public.orders(created_by,idempotency_key) where idempotency_key is not null;
create index orders_created_at_idx on public.orders(created_at desc);
create index orders_status_idx on public.orders(status);
create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null, product_name text not null,
  unit_price numeric(12,2) not null, hpp numeric(12,2), quantity integer not null check(quantity between 1 and 99),
  subtotal numeric(12,2) not null, notes text, created_at timestamptz not null default now()
);
create table public.order_item_toppings (
  id bigint generated by default as identity primary key,
  order_item_id bigint not null references public.order_items(id) on delete cascade,
  topping_id bigint references public.toppings(id) on delete set null, topping_name text not null,
  price numeric(12,2) not null, hpp numeric(12,2), quantity integer not null default 1 check(quantity between 1 and 99),
  created_at timestamptz not null default now()
);
create table public.settings (
  id bigint generated by default as identity primary key,
  key text not null unique, value text, "group" text, description text,
  updated_at timestamptz not null default now()
);
insert into public.settings(key,value,"group") values ('store_status','open','store'),('store_name','WarungCerdas','store'),('pos_name','POS','store') on conflict(key) do nothing;

create or replace function public.current_user_is_active() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and is_active=true)
$$;
create or replace function public.current_user_is_admin() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and is_active=true and role='admin')
$$;
revoke all on function public.current_user_is_active() from public;
revoke all on function public.current_user_is_admin() from public;
grant execute on function public.current_user_is_active() to authenticated;
grant execute on function public.current_user_is_admin() to authenticated;

create or replace function public.create_order(payload jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  actor uuid := auth.uid(); entry jsonb; topping_entry jsonb; product_row public.products%rowtype; topping_row public.toppings%rowtype;
  new_order public.orders%rowtype; line_id bigint; line_qty integer; topping_qty integer; line_sum numeric(12,2);
  computed_subtotal numeric(12,2):=0; computed_discount numeric(12,2):=0; computed_fee numeric(12,2):=0; computed_total numeric(12,2):=0;
  requested_discount numeric(12,2):=coalesce((payload->>'discount_value')::numeric,0); discount_mode text:=nullif(payload->>'discount_type',''); fee_label text:=nullif(trim(payload->>'additional_fee_label'),'');
  method text:=nullif(payload->>'payment_method',''); payment_state text:=coalesce(payload->>'payment_status','unpaid'); paid numeric(12,2); key uuid:=nullif(payload->>'idempotency_key','')::uuid;
  seq integer; order_code text;
begin
  if actor is null or not public.current_user_is_active() then raise exception 'Akun tidak aktif.' using errcode='42501'; end if;
  if coalesce((select value from public.settings where key='store_status'),'open') <> 'open' then raise exception 'Toko sedang tutup.' using errcode='P0001'; end if;
  if jsonb_typeof(payload->'items') <> 'array' or jsonb_array_length(payload->'items')=0 then raise exception 'Keranjang masih kosong.' using errcode='22023'; end if;
  if key is not null then
    select * into new_order from public.orders where created_by=actor and idempotency_key=key;
    if found then return jsonb_build_object('id',new_order.id,'order_number',new_order.order_number,'total',new_order.total); end if;
  end if;
  for entry in select value from jsonb_array_elements(payload->'items') loop
    select * into product_row from public.products where id=(entry->>'product_id')::bigint and is_available=true;
    if not found then raise exception 'Produk tidak tersedia.' using errcode='22023'; end if;
    line_qty := (entry->>'quantity')::integer;
    if line_qty < 1 or line_qty > 99 then raise exception 'Jumlah produk tidak valid.' using errcode='22023'; end if;
    line_sum := product_row.price;
    for topping_entry in select value from jsonb_array_elements(coalesce(entry->'toppings','[]'::jsonb)) loop
      select t.* into topping_row from public.toppings t join public.product_topping pt on pt.topping_id=t.id where t.id=(topping_entry->>'id')::bigint and pt.product_id=product_row.id and t.is_available=true;
      if not found then raise exception 'Topping tidak tersedia untuk produk ini.' using errcode='22023'; end if;
      topping_qty := (topping_entry->>'quantity')::integer;
      if topping_qty < 1 or topping_qty > 99 then raise exception 'Jumlah topping tidak valid.' using errcode='22023'; end if;
      line_sum := line_sum + topping_row.price*topping_qty;
    end loop;
    computed_subtotal := computed_subtotal + line_sum*line_qty;
  end loop;
  if requested_discount < 0 or (discount_mode is not null and discount_mode not in ('fixed','percentage')) or (discount_mode='percentage' and requested_discount>100) or (discount_mode is null and requested_discount>0) then raise exception 'Diskon tidak valid.' using errcode='22023'; end if;
  if discount_mode='percentage' then computed_discount:=round(computed_subtotal*requested_discount/100,2); elsif discount_mode='fixed' then computed_discount:=requested_discount; end if;
  if computed_discount>computed_subtotal then raise exception 'Diskon melebihi subtotal.' using errcode='22023'; end if;
  computed_fee:=coalesce((payload->>'additional_fee_amount')::numeric,0);
  if computed_fee<0 or (computed_fee>0 and fee_label is null) then raise exception 'Biaya tambahan tidak valid.' using errcode='22023'; end if;
  computed_total:=computed_subtotal-computed_discount+computed_fee;
  if payment_state not in ('paid','unpaid') or (method is not null and method not in ('cash','qris')) then raise exception 'Pembayaran tidak valid.' using errcode='22023'; end if;
  if payment_state='paid' and coalesce((payload->>'payment_confirmed')::boolean,false)=false then raise exception 'Konfirmasi pembayaran wajib.' using errcode='22023'; end if;
  if payment_state='paid' and method='cash' then
    paid:=coalesce((payload->>'amount_paid')::numeric,0); if paid<computed_total then raise exception 'Uang tunai kurang dari total.' using errcode='22023'; end if;
  elsif payment_state='paid' and method='qris' then paid:=computed_total;
  elsif payment_state='paid' then raise exception 'Pilih metode pembayaran.' using errcode='22023'; end if;
  perform pg_advisory_xact_lock(hashtext(to_char(now() at time zone 'Asia/Jakarta','YYYYMMDD')));
  select count(*)+1 into seq from public.orders where order_number like 'WC-'||to_char(now() at time zone 'Asia/Jakarta','YYYYMMDD')||'-%';
  order_code:='WC-'||to_char(now() at time zone 'Asia/Jakarta','YYYYMMDD')||'-'||lpad(seq::text,3,'0');
  insert into public.orders(order_number,type,status,customer_name,table_number,delivery_address,delivery_platform,subtotal,total,discount_type,discount_value,discount_amount,additional_fee_label,additional_fee_amount,payment_method,amount_paid,change,payment_status,paid_at,notes,created_by,idempotency_key)
  values(order_code,payload->>'type','preparing',nullif(trim(payload->>'customer_name'),''),nullif(trim(payload->>'table_number'),''),nullif(trim(payload->>'delivery_address'),''),nullif(trim(payload->>'delivery_platform'),''),computed_subtotal,computed_total,discount_mode,requested_discount,computed_discount,case when computed_fee>0 then fee_label end,computed_fee,method,paid,case when payment_state='paid' and method='cash' then paid-computed_total when payment_state='paid' then 0 end,payment_state,case when payment_state='paid' then now() end,nullif(trim(payload->>'notes'),''),actor,key) returning * into new_order;
  for entry in select value from jsonb_array_elements(payload->'items') loop
    select * into product_row from public.products where id=(entry->>'product_id')::bigint;
    line_qty := (entry->>'quantity')::integer; line_sum := product_row.price;
    for topping_entry in select value from jsonb_array_elements(coalesce(entry->'toppings','[]'::jsonb)) loop
      select t.* into topping_row from public.toppings t where id=(topping_entry->>'id')::bigint;
      line_sum:=line_sum+topping_row.price*(topping_entry->>'quantity')::integer;
    end loop;
    insert into public.order_items(order_id,product_id,product_name,unit_price,hpp,quantity,subtotal,notes) values(new_order.id,product_row.id,product_row.name,product_row.price,product_row.hpp,line_qty,line_sum*line_qty,nullif(trim(entry->>'notes'),'')) returning id into line_id;
    for topping_entry in select value from jsonb_array_elements(coalesce(entry->'toppings','[]'::jsonb)) loop
      select * into topping_row from public.toppings where id=(topping_entry->>'id')::bigint;
      insert into public.order_item_toppings(order_item_id,topping_id,topping_name,price,hpp,quantity) values(line_id,topping_row.id,topping_row.name,topping_row.price,topping_row.hpp,(topping_entry->>'quantity')::integer);
    end loop;
  end loop;
  return jsonb_build_object('id',new_order.id,'order_number',new_order.order_number,'total',new_order.total);
end $$;
revoke all on function public.create_order(jsonb) from public;
grant execute on function public.create_order(jsonb) to authenticated;

